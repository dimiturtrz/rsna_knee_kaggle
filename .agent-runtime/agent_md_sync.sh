#!/usr/bin/env bash
# .agent-runtime/agent_md_sync.sh — propagate CLAUDE.md outward, then rebuild the tier stack.
#
# CLAUDE.md IS THE SOURCE OF TRUTH. Instructions are authored there and copied out
# to every other name a harness happens to auto-load; nothing flows back. Claude Code
# walks UP the directory tree from cwd and auto-loads every CLAUDE.md (global → parent
# → project). Kimi auto-loads only the project's AGENTS.md, so both the other name AND
# the upward tiers have to be generated for it. This script:
#   1. Copies CLAUDE.md → AGENTS.md (one direction, always).
#   2. Concatenates the tier chain (global → ... → project) into
#      .agent-runtime/AGENTS_STACK.md for the SessionStart hook to inject.
#
# A hand-edit to AGENTS.md is destroyed by the next run, silently and with no way to
# recover it if it was never committed — so step 1 REFUSES when AGENTS.md has changed
# without CLAUDE.md changing too, and says which file to move the edit into. That guard
# is the whole reason this is a script and not a `cp`: the direction being obvious to
# whoever wrote it is exactly what makes the overwrite invisible to whoever did not.
#
# Usage: bash .agent-runtime/agent_md_sync.sh [--force]
#   --force  overwrite AGENTS.md even if it holds edits CLAUDE.md does not
# Output: AGENTS.md (generated), .agent-runtime/AGENTS_STACK.md (generated)

set -u

FORCE=0
if [ "${1:-}" = "--force" ]; then
  FORCE=1
fi

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
REPO="$(cd "$SCRIPT_DIR/.." && pwd)"
OUT="$SCRIPT_DIR/AGENTS_STACK.md"

# --- 1. CLAUDE.md -> AGENTS.md, one direction ---
if [ ! -f "$REPO/CLAUDE.md" ]; then
  echo "FATAL: $REPO/CLAUDE.md is missing; it is the source of truth and nothing can be generated" >&2
  exit 1
fi

if ! diff -q "$REPO/CLAUDE.md" "$REPO/AGENTS.md" >/dev/null 2>&1; then
  # AGENTS.md is tracked, so git can tell an edit made THERE apart from one that simply
  # has not been propagated yet. Untracked or no git: fall through and copy.
  if [ "$FORCE" -eq 0 ] && git -C "$REPO" rev-parse --git-dir >/dev/null 2>&1; then
    AGENTS_DIRTY=$(git -C "$REPO" diff --name-only HEAD -- AGENTS.md)
    CLAUDE_DIRTY=$(git -C "$REPO" diff --name-only HEAD -- CLAUDE.md)
    if [ -n "$AGENTS_DIRTY" ] && [ -z "$CLAUDE_DIRTY" ]; then
      echo "REFUSING: AGENTS.md has uncommitted edits and CLAUDE.md does not." >&2
      echo "  AGENTS.md is GENERATED. Move the edit into CLAUDE.md and re-run," >&2
      echo "  or pass --force to discard it. Diff:" >&2
      git -C "$REPO" --no-pager diff -- AGENTS.md >&2
      exit 1
    fi
  fi
  cp "$REPO/CLAUDE.md" "$REPO/AGENTS.md"
  echo "propagated AGENTS.md <- CLAUDE.md"
fi

# --- 2. Tier chain: walk UP for CLAUDE.md, global tier first ---
declare -a FOUND=()
DIR="$REPO"
while true; do
  CANDIDATE="$DIR/CLAUDE.md"
  if [ -f "$CANDIDATE" ] && [ -s "$CANDIDATE" ]; then
    FOUND+=("$CANDIDATE")
  fi
  PARENT="$(dirname "$DIR")"
  if [ "$PARENT" = "$DIR" ]; then
    break
  fi
  DIR="$PARENT"
done

# Reverse: collected project -> root, emit root -> ... -> project, global tier first
# (Claude's load order: global -> parent dirs -> project).
REV=()
for (( i=${#FOUND[@]}-1; i>=0; i-- )); do
  REV+=("${FOUND[$i]}")
done

GLOBAL="${HOME}/.claude/CLAUDE.md"
if [ -f "$GLOBAL" ] && [ -s "$GLOBAL" ]; then
  REV=("$GLOBAL" "${REV[@]}")
fi

{
  echo "# Kimi context stack — auto-generated by agent_md_sync.sh"
  echo "# Generated: $(date -Iseconds)"
  echo "# Do NOT edit by hand; regenerate with bash .agent-runtime/agent_md_sync.sh"
  echo ""
  for f in "${REV[@]}"; do
    echo "==============================================================="
    echo " CLAUDE.md tier: ${f/#$HOME/~}"
    echo "==============================================================="
    echo ""
    cat "$f"
    echo ""
  done
} > "$OUT"

LINES=$(wc -l < "$OUT")
echo "stack: $LINES lines into $OUT"
for f in "${REV[@]}"; do
  echo "  - ${f/#$HOME/~}"
done
