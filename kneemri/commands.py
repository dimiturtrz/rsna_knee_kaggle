"""Every `python -m` entrypoint the package has, generated from the modules themselves.

Run as `python -m kneemri.commands` to rewrite `kneemri/README.md`, or with `--check` to assert it is
current — the same shape `archmap` uses, and for the same reason: a hand-written index of forty-two
commands is a promise to update it forty-two times.

IT EXISTS BECAUSE FOURTEEN OF THEM WERE INVISIBLE. `decode_bench`, `fetch_bench`, `serve_bench`,
`diagnose_laterality`, `diagnose_matrix`, `slot_ties`, `build_embeddings`, `report_embeddings`,
`encoder_drift`, `paired_floor`, `tie_divergence`, `holdout_backfill`, `dry_run` and `confident_labels`
appeared in no markdown in the repository. A tool nobody can find is a tool somebody writes again, and
each of those answers a question this project has already paid to answer once.

The one-line summary is the module's own docstring first line, never a second description kept beside
it. That is what makes the index unable to drift: there is nothing to keep in sync.
"""

import argparse
import ast
import logging
from pathlib import Path

logger = logging.getLogger(__name__)

ENTRYPOINT = "main"
GROUP_HEADING = "###"
INDEX = Path("kneemri/README.md")
NESTED = 2  # `kneemri.corpus.probe` — a module deeper than `kneemri.tool` groups under its subpackage.
PACKAGE = Path("kneemri")

PREAMBLE = """# kneemri — the commands

Generated by `python -m kneemri.commands`; `--check` asserts it is current, and CI runs that. Each
summary is the module's own docstring first line, so this file cannot describe a command differently
from the command itself.

The training arms are NOT here — they are shell recipes over `kneemri.training.train`, and
`experiments/README.md` is their ledger.
"""


class Commands:
    """The package's `python -m` entrypoints, discovered by parsing rather than by importing.

    Parsed, because importing forty-two modules to list them would pull torch, CUDA and every optional
    dependency into what is meant to be a documentation step — and would fail on the first module whose
    import has a side effect.
    """

    def __init__(self, package: Path = PACKAGE) -> None:
        self.package = package

    def entries(self) -> list[tuple[str, str]]:
        """Every module defining a top-level `main`, as (dotted module, its docstring's first line).

        Sorted by module so the generated table has a stable order: an index whose rows move around
        produces a diff on every regeneration and stops being reviewable.
        """
        found = []
        for path in sorted(self.package.rglob("*.py")):
            tree = ast.parse(path.read_text(encoding="utf-8"))
            if not any(isinstance(node, ast.FunctionDef) and node.name == ENTRYPOINT for node in tree.body):
                continue
            module = ".".join(path.relative_to(self.package.parent).with_suffix("").parts)
            summary = (ast.get_docstring(tree) or "").split("\n")[0]
            found.append((module, summary))
        return found

    def rendered(self) -> str:
        """The index as markdown, grouped by subpackage."""
        grouped: dict[str, list[tuple[str, str]]] = {}
        for module, summary in self.entries():
            parts = module.split(".")
            grouped.setdefault(parts[1] if len(parts) > NESTED else parts[0], []).append((module, summary))
        lines = [PREAMBLE]
        for group, rows in sorted(grouped.items()):
            lines.append(f"{GROUP_HEADING} {group}\n")
            lines.append("| command | what it answers |")
            lines.append("|---|---|")
            lines.extend(f"| `python -m {module}` | {summary} |" for module, summary in rows)
            lines.append("")
        return "\n".join(lines)

    def stale(self, index: Path = INDEX) -> bool:
        """Whether the written index disagrees with what the modules now say."""
        return not index.exists() or index.read_text(encoding="utf-8") != self.rendered()

    def write(self, index: Path = INDEX) -> None:
        """Rewrite the index from the modules."""
        index.write_text(self.rendered(), encoding="utf-8")


def main() -> None:
    """Regenerate the command index, or assert it is current."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the index is out of date")
    parser.add_argument("--index", type=Path, default=INDEX)
    parser.add_argument("--package", type=Path, default=PACKAGE)
    arguments = parser.parse_args()
    logging.basicConfig(level=logging.INFO, format="%(message)s")

    commands = Commands(arguments.package)
    if not arguments.check:
        commands.write(arguments.index)
        logger.info("%s: %d commands", arguments.index, len(commands.entries()))
        return
    if commands.stale(arguments.index):
        message = f"{arguments.index} is out of date; run `python -m kneemri.commands`"
        raise SystemExit(message)
    logger.info("%s is current (%d commands)", arguments.index, len(commands.entries()))


if __name__ == "__main__":
    main()
